const RTL_LANGS = ['ar']

const DEFAULT_LANG = 'en'

function detectLang() {
    const requested = new URLSearchParams(window.location.search).get('lang')
    return TRANSLATIONS[requested] ? requested : DEFAULT_LANG
}

function applyTranslations(lang) {
    const dict = TRANSLATIONS[lang]
    document.documentElement.lang = lang
    document.documentElement.dir = RTL_LANGS.includes(lang) ? 'rtl' : 'ltr'

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n')
        const value = dict[key]
        if (value === undefined) return

        const attrList = el.getAttribute('data-i18n-attr')
        if (attrList) {
            attrList.split(',').forEach((attr) => el.setAttribute(attr.trim(), value))
        } else {
            el.textContent = value
            if (el.tagName === 'LABEL') el.title = value
        }
    })
}

const CURRENT_LANG = detectLang()
applyTranslations(CURRENT_LANG)
